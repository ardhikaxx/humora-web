    /**
     * Seed all imported HUMORA video content.
     *
     * Video files are generated through FileStorageService (VP9/Opus WebM),
     * and every series uses a WebP thumbnail derived from the default image.
     */
    public function run(): void
    {
        $categories = [];

        foreach ($this->categoryData() as $category) {
            $categories[$category['slug']] = Category::firstOrCreate(
                ['slug' => $category['slug']],
                [
                    'name' => $category['name'],
                    'description' => $category['description'],
                    'is_active' => true,
                ]
            );
        }

        DB::transaction(function () use ($categories) {
            Episode::query()->delete();
            DB::table('category_series')->delete();
            Series::query()->delete();

            foreach ($this->seriesData() as $seriesData) {
                $categorySlugs = $seriesData['categories'];
                $episodes = $seriesData['episodes'];
                unset($seriesData['categories'], $seriesData['episodes']);

                $series = Series::create($seriesData);

                $series->categories()->sync(array_map(
                    static fn (string $slug): int => $categories[$slug]->id,
                    $categorySlugs
                ));

                foreach ($episodes as $episode) {
                    $episode['series_id'] = $series->id;
                    $episode['access_type'] = $episode['episode_number'] <= 2 ? 'free' : 'premium';
                    Episode::create($episode);
                }
            }
        });
    }

